"""Join official static/dynamic relations with big SK or the native seat SK route."""
from pathlib import Path
from collections import Counter
import hashlib
import json
import subprocess

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / 'tmp/ten-year-userscript-audit-20261120/decoded'
paths = [DATA / 'GameItemConfig.json', DATA / 'GeneralSkinInfoConfig.json',
         ROOT / 'tmp/sgs10-skins-20261118/version.json',
         ROOT / 'electron-next/src/features/ten-year-static-catalog.js']
items = json.loads(paths[0].read_bytes())['ItemConf']
skin_config = json.loads(paths[1].read_bytes())
skins = {r['SkinID']: r for r in skin_config['SkinConf']}
spine_by_id = {r['SkinID']: r for r in skin_config['SkinSpineConf']}
versions = json.loads(paths[2].read_bytes())
static = json.loads(subprocess.check_output(['node', '-e',
    'process.stdout.write(JSON.stringify(require(process.argv[1])()))', str(paths[3])], encoding='utf-8'))
static_rows = {r[0]: r for r in static['skins']}
by_item = {r['ItemID']: r for r in items}
rows, audit, seen = [], [], set()
for item in items:
    if item.get('IsLimit') or item.get('SkinID') not in static_rows or not item.get('RelationSkinItemID'):
        continue
    target = by_item.get(item['RelationSkinItemID'], {})
    dynamic = skins.get(target.get('SkinID'), {})
    source_id = dynamic.get('SkinID')
    resource = str(dynamic.get('Resource') or '')
    note = {'staticId': item['SkinID'], 'itemId': item['ItemID'], 'relatedItemId': item['RelationSkinItemID'],
            'dynamicId': source_id, 'resource': resource}
    prefix = 'res/assets/runtime/general/big/dynamic/' + resource + '/'
    if dynamic.get('SkinGradeType') not in [7, 8, 10]:
        note['state'] = 'not-dynamic-relation'
    else:
        # The official item relation identifies the static fallback. BigResource is
        # a maxBig image and is deliberately not used to infer this relation.
        layers = []
        if all(prefix + 'daiji.' + ext in versions for ext in ['sk', 'png']):
            mode = 'big'
            for file in ['beijing', 'daiji', 'qianjing']:
                if all(prefix + file + '.' + ext in versions for ext in ['sk', 'png']):
                    layers.append({'file': file + '.sk', 'version': versions[prefix + file + '.sk']})
            note['state'] = 'big-sk-candidate-check-on-selection'
        elif dynamic.get('ShowFrame'):
            # Verified GeneralAvatarSprite.loadSkeleton: ShowFrame uses the first
            # SmallStandByAnimateInfos.FileName or daiji2.sk, played at index 0.
            # The old manifest is a cache snapshot, not a list of all online files.
            small = sorted(spine_by_id.get(source_id, {}).get('SmallStandByAnimateInfos') or [],
                           key=lambda r: r.get('Index', 0))
            file = small[0]['FileName'] if small else 'daiji2'
            if '.' not in file:
                file += '.sk'
            if not file.endswith('.sk'):
                note['state'] = 'unsupported-native-seat-format'
                audit.append(note)
                continue
            mode = 'seat'
            layers = [{'file': file, 'version': versions.get(prefix + file, ''), 'animationIndex': 0}]
            pair = all(prefix + file[:-3] + '.' + ext in versions for ext in ['sk', 'png'])
            note['state'] = 'seat-sk-manifest-check-on-selection' if pair else 'seat-sk-check-on-selection'
        else:
            note['state'] = 'no-supported-native-seat-route'
            audit.append(note)
            continue
        key = (item['SkinID'], source_id)
        if key not in seen:
            seen.add(key)
            row = static_rows[item['SkinID']][:]
            row[0] = 'dynamic:' + str(source_id)
            row[2] = '动态·' + row[2]
            row.append({'id': source_id, 'resource': resource, 'layers': layers, 'staticId': item['SkinID'], 'mode': mode})
            rows.append(row)
    audit.append(note)
hashes = {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in paths}
rows.sort(key=lambda row: row[9]['id'])
out = ROOT / 'electron-next/src/features/ten-year-dynamic-catalog.js'
out.write_text('// Generated by scripts/build-ten-year-dynamic-catalog.py; big/seat SK candidates checked on selection.\n'
    '// Source SHA256: ' + json.dumps(hashes) + '\n'
    'module.exports = function getTenYearDynamicCatalog() { return '
    + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + '; };\n', encoding='utf-8')
related_ids = {r['dynamicId'] for r in audit}
all_relations = {by_item.get(i.get('RelationSkinItemID'), {}).get('SkinID') for i in items if not i.get('IsLimit')}
outside = [{'dynamicId': r['SkinID'], 'name': r['ItemName'], 'state':
            'no-same-name-static-fallback' if r['SkinID'] in all_relations else 'no-official-static-item-relation'}
           for r in skins.values() if r['SkinGradeType'] in [7, 8, 10] and r['SkinID'] not in related_ids]
report = {'sourceSha256': hashes, 'summary': dict(Counter(r['state'] for r in audit + outside)),
          'candidates': len(rows), 'relations': audit, 'outsideScope': outside}
(ROOT / 'tmp/ten-year-userscript-audit-20261120/dynamic-catalog-audit.json').write_text(
    json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
print(json.dumps({'candidates': len(rows), **report['summary']}))
